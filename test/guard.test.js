import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, writeFile, rm, mkdir, readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { classifyTarget, contentHash, stamp, mayWrite } from '../src/guard.js';

/**
 * `fix` writes into the user's repository. Overwriting a file they edited by hand
 * loses work silently — no test fails, nothing warns them. A content hash makes it
 * decidable.
 */

async function tempFile(body) {
  const dir = await mkdtemp(join(tmpdir(), 'crucible-guard-'));
  const path = join(dir, 'x.test.js');
  await writeFile(path, body, 'utf8');
  return { dir, path };
}

test('an absent target is written', async () => {
  const dir = await mkdtemp(join(tmpdir(), 'crucible-guard-'));
  try {
    const decision = await mayWrite(join(dir, 'nope.test.js'));
    assert.equal(decision.write, true);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test('a file without our marker is not ours', async (t) => {
  const { dir, path } = await tempFile('// some other tool\nassert(1);\n');
  t.after(() => rm(dir, { recursive: true, force: true }));

  assert.equal(await classifyTarget(path), 'user');
  const decision = await mayWrite(path);
  assert.equal(decision.write, false);
  assert.match(decision.reason, /not generated by crucible/);
});

test('a freshly stamped file is clean and replaceable', async (t) => {
  const { dir, path } = await tempFile(stamp('// Generated by crucible\nassert(1);\n'));
  t.after(() => rm(dir, { recursive: true, force: true }));

  assert.equal(await classifyTarget(path), 'generated-clean');
  assert.equal((await mayWrite(path)).write, true);
});

test('an edited generated file is left alone', async (t) => {
  const stamped = stamp('// Generated by crucible\nassert(1);\n');
  const edited = `${stamped}// my hand-written case\n`;
  const { dir, path } = await tempFile(edited);
  t.after(() => rm(dir, { recursive: true, force: true }));

  assert.equal(await classifyTarget(path), 'generated-edited');
  const decision = await mayWrite(path);
  assert.equal(decision.write, false);
  assert.match(decision.reason, /edited after it was written/);

  const after = await readFile(path, 'utf8');
  assert.match(after, /my hand-written case/, 'the edit must survive');
});

test('--force overwrites an edited file', async (t) => {
  const stamped = stamp('// Generated by crucible\nassert(1);\n');
  const { dir, path } = await tempFile(`${stamped}// edit\n`);
  t.after(() => rm(dir, { recursive: true, force: true }));

  assert.equal((await mayWrite(path, { force: true })).write, true);
});

test('a python-stamped file is recognised', async (t) => {
  const body = '"""Boundary tests.\n\nGenerated by crucible.\n"""\nassert True\n';
  const { dir, path } = await tempFile(stamp(body, 'py'));
  t.after(() => rm(dir, { recursive: true, force: true }));

  assert.equal(await classifyTarget(path), 'generated-clean');
});

test('the hash ignores whitespace after the last line', () => {
  // Trailing newlines must not change the identity of the content.
  const a = contentHash('line one\nline two\n');
  const b = contentHash('line one\nline two\n\n\n');
  assert.equal(a, b);
});

test('removing a line changes the hash', () => {
  assert.notEqual(contentHash('a\nb\n'), contentHash('a\n'));
});

test('a file written before hashes existed is treated as edited, not clean', async (t) => {
  // Safer to skip than to overwrite: we cannot prove it is untouched.
  const { dir, path } = await tempFile('// Generated by crucible\nassert(1);\n');
  t.after(() => rm(dir, { recursive: true, force: true }));

  assert.equal(await classifyTarget(path), 'generated-edited');
  assert.equal((await mayWrite(path)).write, false);
});
