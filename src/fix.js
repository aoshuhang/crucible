/**
 * The fixer: turn "this test asserts nothing" into "this test pins the value".
 *
 * A surviving mutation means the suite does not care what a line computes.
 * The mechanical repair is to pin the exact output, so any change to that line
 * breaks the test. We do that by:
 *
 *   1. harvesting call sites already present in the test file
 *      (`computeStats(createGenome(1))`), so we reuse real, valid inputs
 *   2. evaluating them against the ORIGINAL source to get golden values
 *   3. emitting a test file that asserts exact equality
 *
 * The result is verified, not assumed: the caller re-runs the mutation audit and
 * compares scores. If the new test does not kill the mutants, we say so instead
 * of claiming a fix.
 */

import { readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import { join, dirname, basename, extname, relative } from 'node:path';

/** Functions exported by a source file, best effort. */
export function exportedNames(source) {
  const names = new Set();
  const patterns = [
    /export\s+(?:async\s+)?function\s+(\w+)/g,
    /export\s+const\s+(\w+)\s*=/g,
    /export\s+let\s+(\w+)\s*=/g,
    /export\s+class\s+(\w+)/g,
    /^def\s+(\w+)/gm,
  ];
  for (const re of patterns) {
    re.lastIndex = 0;
    let m;
    while ((m = re.exec(source)) !== null) names.add(m[1]);
  }
  return [...names];
}

/**
 * Find call sites in a test file that invoke one of `names`.
 * Returns the raw argument text so we can paste it back verbatim and keep the
 * exact same inputs the existing tests already trust.
 * @returns {{ fn: string, args: string, call: string }[]}
 */
export function harvestCallSites(testSource, names) {
  const out = [];
  const seen = new Set();

  for (const fn of names) {
    const re = new RegExp(`\\b${fn}\\s*\\(`, 'g');
    re.lastIndex = 0;
    let m;
    while ((m = re.exec(testSource)) !== null) {
      // Walk forward balancing parens to capture the full argument list.
      let depth = 0;
      let i = m.index + m[0].length - 1;
      let args = '';
      for (; i < testSource.length; i += 1) {
        const ch = testSource[i];
        if (ch === '(') depth += 1;
        else if (ch === ')') {
          depth -= 1;
          if (depth === 0) break;
        } else if (depth === 1) {
          args += ch;
        }
      }

      const call = `${fn}(${args})`;
      if (args.trim() === '' || seen.has(call)) continue;
      if (args.includes('=>') || args.includes('function')) continue;
      seen.add(call);
      out.push({ fn, args: args.trim(), call });
    }
  }

  return out;
}

/**
 * Build a probe that the project's runner will accept as a valid test.
 *
 * It has to be a real test file: `node --test`, vitest and jest all refuse a file
 * with no test in it, and a failing probe means we cannot read any values.
 * The probe asserts nothing meaningful; it prints the values and passes.
 */
export function buildProbe({ importPath, sites, runner = 'node' }) {
  const lines = [];
  lines.push('// generated by crucible — temporary probe, safe to delete');

  if (runner === 'vitest' || runner === 'jest') {
    lines.push("import { it } from 'vitest';");
    lines.push(`import * as mod from '${importPath}';`);
    lines.push("it('probe', () => {");
    lines.push('  const out = [];');
    for (const site of sites) {
      lines.push('  try {');
      lines.push(`    out.push({ call: ${JSON.stringify(site.call)}, value: mod.${site.fn}(${site.args}) });`);
      lines.push('  } catch (e) {');
      lines.push(`    out.push({ call: ${JSON.stringify(site.call)}, error: String(e && e.message) });`);
      lines.push('  }');
    }
    lines.push("  console.log('CRUCIBLE_PROBE' + JSON.stringify(out));");
    lines.push('});');
    return lines.join('\n');
  }

  // node:test style
  lines.push("import { test } from 'node:test';");
  lines.push(`import * as mod from '${importPath}';`);
  lines.push("test('probe', () => {");
  lines.push('  const out = [];');
  for (const site of sites) {
    lines.push('  try {');
    lines.push(`    out.push({ call: ${JSON.stringify(site.call)}, value: mod.${site.fn}(${site.args}) });`);
    lines.push('  } catch (e) {');
    lines.push(`    out.push({ call: ${JSON.stringify(site.call)}, error: String(e && e.message) });`);
    lines.push('  }');
  }
  lines.push("  console.log('CRUCIBLE_PROBE' + JSON.stringify(out));");
  lines.push('});');
  return lines.join('\n');
}

/** Extract the probe payload from runner output. */
export function parseProbeOutput(text) {
  const idx = text.indexOf('CRUCIBLE_PROBE');
  if (idx === -1) return null;
  const rest = text.slice(idx + 'CRUCIBLE_PROBE'.length);
  // The JSON ends at the last ']' before any trailing runner noise.
  const end = rest.lastIndexOf(']');
  if (end === -1) return null;
  try {
    return JSON.parse(rest.slice(0, end + 1));
  } catch {
    return null;
  }
}

/** Render a value as an exact assertion literal. */
function literal(value) {
  if (typeof value === 'number') {
    return Number.isInteger(value) ? String(value) : String(value);
  }
  return JSON.stringify(value);
}

/**
 * Emit a permanent regression test that pins every harvested call's output.
 * Follows the project's own test framework so the file actually runs.
 * Numbers use closeness for float safety; strings and booleans use equality.
 */
export function buildFixTest({ importPath, probed, sourceName, runner = 'node' }) {
  const isVitest = runner === 'vitest' || runner === 'jest';
  const lines = [];

  lines.push(`// Regression tests for ${sourceName}.`);
  lines.push('// Generated by crucible: these pin exact values so a silent change in');
  lines.push('// behaviour breaks the suite instead of slipping through.');

  if (isVitest) {
    lines.push("import { describe, expect, it } from 'vitest';");
  } else {
    lines.push("import { describe, it } from 'node:test';");
    lines.push("import assert from 'node:assert/strict';");
  }

  lines.push(`import * as mod from '${importPath}';`);
  lines.push('');
  lines.push(`describe('${sourceName} exact values', () => {`);

  // Render one assertion in the project's dialect.
  const assertNumber = (expr, v) => (isVitest
    ? `expect(${expr}).toBeCloseTo(${v}, 6);`
    : `assert.ok(Math.abs(${expr} - ${v}) < 1e-6, 'expected ' + ${v} + ', got ' + ${expr});`);
  const assertEqual = (expr, v) => (isVitest
    ? `expect(${expr}).toBe(${v});`
    : `assert.equal(${expr}, ${v});`);

  for (const entry of probed) {
    if (entry.error) continue;
    const value = entry.value;

    if (typeof value === 'number') {
      lines.push(`  it('${entry.call} returns ${literal(value)}', () => {`);
      lines.push(`    ${assertNumber(`mod.${entry.call}`, literal(value))}`);
      lines.push('  });');
      lines.push('');
      continue;
    }

    if (value === null || value === undefined || typeof value !== 'object') {
      lines.push(`  it('${entry.call} returns ${literal(value)}', () => {`);
      lines.push(`    ${assertEqual(`mod.${entry.call}`, literal(value))}`);
      lines.push('  });');
      lines.push('');
      continue;
    }

    // Object: pin scalar leaves so the failure message stays readable.
    const leaves = Object.entries(value)
      .filter(([, v]) => typeof v === 'number' || typeof v === 'string' || typeof v === 'boolean')
      .slice(0, 40);

    if (leaves.length === 0) continue;

    lines.push(`  it('${entry.call} returns its exact shape', () => {`);
    lines.push(`    const r = mod.${entry.call};`);
    for (const [key, v] of leaves) {
      const access = /^[A-Za-z_$][\w$]*$/.test(key) ? `r.${key}` : `r[${JSON.stringify(key)}]`;
      lines.push(`    ${typeof v === 'number' ? assertNumber(access, literal(v)) : assertEqual(access, literal(v))}`);
    }
    lines.push('  });');
    lines.push('');
  }

  lines.push('});');
  return lines.join('\n');
}

/**
 * Emit boundary tests that pin the exact return value at the threshold and its
 * neighbours.
 *
 * Pinning `isFull(5)` looks responsible and catches nothing. To kill
 * `count >= MAX` → `count > MAX` the test must call with exactly MAX. So we call
 * the function at below/at/above and pin whatever the original code returns.
 *
 * @param {object} opts
 * @param {string} opts.importPath
 * @param {string} opts.sourceName
 * @param {string} opts.runner
 * @param {{ fn: string, op: string, constantName: string, values: {at:number,below:number,above:number}, observed: any[] }[]} opts.cases
 */
export function buildBoundaryTest({ importPath, sourceName, runner = 'node', cases }) {
  const isVitest = runner === 'vitest' || runner === 'jest';
  const lines = [];

  lines.push(`// Boundary tests for ${sourceName}.`);
  lines.push('// Generated by crucible: these call at the exact threshold and its neighbours,');
  lines.push('// which is the only way to catch an off-by-one in a comparison.');
  if (isVitest) {
    lines.push("import { describe, expect, it } from 'vitest';");
  } else {
    lines.push("import { describe, it } from 'node:test';");
    lines.push("import assert from 'node:assert/strict';");
  }
  lines.push(`import * as mod from '${importPath}';`);
  lines.push('');

  const pin = (expr, v) => {
    if (typeof v === 'number') {
      return isVitest
        ? `expect(${expr}).toBeCloseTo(${v}, 6);`
        : `assert.ok(Math.abs(${expr} - ${v}) < 1e-6);`;
    }
    if (v === null || v === undefined || typeof v !== 'object') {
      return isVitest ? `expect(${expr}).toBe(${JSON.stringify(v)});` : `assert.equal(${expr}, ${JSON.stringify(v)});`;
    }
    return null;
  };

  for (const c of cases) {
    lines.push(`describe('${sourceName}.${c.fn} at the ${c.constantName} boundary', () => {`);

    const points = [
      ['one below the threshold', c.values.below],
      ['exactly at the threshold', c.values.at],
      ['one above the threshold', c.values.above],
    ];

    for (let i = 0; i < points.length; i += 1) {
      const [label, input] = points[i];
      const observed = c.observed[i];
      if (observed === undefined) continue;

      lines.push(`  it('${label} (${input}) returns ${JSON.stringify(observed)}', () => {`);
      const assertion = pin(`mod.${c.fn}(${input})`, observed);
      if (!assertion) {
        lines.push('    // unrepresentable value, skipped');
      } else {
        lines.push(`    ${assertion}`);
      }
      lines.push('  });');
      lines.push('');
    }

    lines.push('});');
    lines.push('');
  }

  return lines.join('\n');
}

/**
 * Build the probe that reads real return values at boundary inputs.
 *
 * The probe is a plain script, not a test file. Running it through the project's
 * test runner fails when crucible is itself running inside a test (node:test refuses
 * to nest runs), and it needlessly drags in the whole suite. A plain module that
 * imports the source and prints JSON works under every runner.
 */
export function buildBoundaryProbe({ importPath, cases }) {
  const lines = [];

  lines.push('// generated by crucible — temporary boundary probe, safe to delete');
  lines.push(`import * as mod from '${importPath}';`);
  lines.push('const out = [];');
  for (const c of cases) {
    for (const input of [c.values.below, c.values.at, c.values.above]) {
      lines.push('try {');
      lines.push(`  out.push({ fn: ${JSON.stringify(c.fn)}, input: ${input}, value: mod.${c.fn}(${input}) });`);
      lines.push('} catch (e) {');
      lines.push(`  out.push({ fn: ${JSON.stringify(c.fn)}, input: ${input}, error: String(e && e.message) });`);
      lines.push('}');
    }
  }
  lines.push("console.log('CRUCIBLE_PROBE' + JSON.stringify(out));");
  return lines.join('\n');
}

/**
 * For a comparison inside a function that takes an object, emit the concrete test
 * a human should paste. "Write a boundary test" helps nobody; showing the exact
 * input and assertion is the whole value.
 *
 * We cannot run these automatically (the argument shape is project-specific), so
 * they are printed as a patch the user can apply.
 */
export function suggestManualBoundary({ fn, comparison, sourceLines }) {
  const line = sourceLines[comparison.line - 1] ?? '';
  const flipped = { '<': '<=', '<=': '<', '>': '>=', '>=': '>', '===': '!==', '!==': '===', '==': '!=', '!=': '==' };

  const left = comparison.left;
  const right = comparison.right;
  const current = comparison.op;
  const other = flipped[current] ?? current;

  return {
    fn,
    line: comparison.line,
    expression: `${left} ${current} ${right}`,
    reason: `${current} and ${other} differ only when ${left} equals ${right}, and no test supplies that exact case`,
    sketch: [
      `// ${fn}: ${left} ${current} ${right} is untested at its edge`,
      `// The ${current} and ${other} versions disagree only at ${left} === ${right}.`,
      `// Supply an argument where ${left} is exactly ${right}, and one just past it.`,
      `// Then assert the two outcomes differ.`,
    ].join('\n'),
    snippet: line.trim().slice(0, 120),
  };
}

/**
 * Where to write the probe and the fix, given the project's conventions.
 */
export function placement({ sourceFile, testFiles, root }) {
  const ext = extname(sourceFile);

  // Follow the project's own extension so a .js project does not get a .ts probe
  // that its runner cannot parse.
  const isTs = ext === '.ts' || ext === '.tsx';
  const suffix = isTs ? '.test.ts' : '.test.js';
  const probeExt = isTs ? '.test.ts' : '.test.js';

  // Prefer the directory the project already keeps its tests in.
  const near = testFiles.find((t) => /\/(tests?|__tests__)\//.test(t));
  const dir = near ? dirname(near) : dirname(sourceFile);
  const base = basename(sourceFile).replace(/\.[^.]+$/, '');
  const fixPath = join(dir, `${base}.exact${suffix}`);

  // Import path from the fix file back to the source.
  // Node ESM requires the extension, so keep it for .js/.mjs projects and strip it
  // only for TypeScript, where the bundler resolves the .ts file.
  let rel = relative(dir, sourceFile).replace(/\\/g, '/');
  if (isTs) rel = rel.replace(/\.(ts|tsx)$/, '');
  if (!rel.startsWith('.')) rel = `./${rel}`;

  return { fixPath, importPath: rel, dir, probeName: `__crucible_probe${probeExt}` };
}
